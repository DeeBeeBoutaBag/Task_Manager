"""A small task API backed by an in-memory dictionary."""

import logging
from datetime import datetime, timezone
from pathlib import Path
from threading import Lock
from typing import Annotated
from uuid import UUID, uuid4

from fastapi import (
    BackgroundTasks,
    Depends,
    FastAPI,
    HTTPException,
    Query,
    Request,
    Response,
    status,
)
from fastapi.exceptions import RequestValidationError
from fastapi.responses import JSONResponse
from pydantic import (
    BaseModel,
    ConfigDict,
    Field,
    StringConstraints,
    ValidationInfo,
    field_validator,
)
from starlette.exceptions import HTTPException as StarletteHTTPException

logger = logging.getLogger(__name__)
LOG_FILE = Path(__file__).with_name("task_events.log")
_log_lock = Lock()

# Reuse the same title rule for creation and updates. A few spaces is not a title.
NonBlankTitle = Annotated[
    str, StringConstraints(strip_whitespace=True, min_length=1)
]


class TaskCreate(BaseModel):
    """Fields the caller can set when creating a task."""

    # Catch typos and reject server-owned fields such as id and created_at.
    model_config = ConfigDict(extra="forbid")

    title: NonBlankTitle
    description: str | None = None
    completed: bool = False


class Task(TaskCreate):
    """The stored task, including the values generated by the server."""

    # Generate a fresh ID and current UTC timestamp for each new task.
    id: UUID = Field(default_factory=uuid4)
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


class TaskUpdate(BaseModel):
    """All fields may be omitted, but only description may be cleared with null."""

    model_config = ConfigDict(extra="forbid")

    title: NonBlankTitle | None = None
    description: str | None = None
    completed: bool | None = None

    @field_validator("title", "completed")
    @classmethod
    def reject_null(cls, value: str | bool | None, info: ValidationInfo) -> str | bool:
        # Pydantic skips default values here. This runs only for supplied fields,
        # so leaving out title is fine, while sending {"title": null} is not.
        if value is None:
            raise ValueError(f"{info.field_name} cannot be null")
        return value


class ErrorResponse(BaseModel):
    detail: str


class TaskPage(BaseModel):
    """One page of tasks, plus the offsets needed to move between pages."""

    total: int
    items: list[Task]
    limit: int
    offset: int
    next_offset: int | None
    previous_offset: int | None


app = FastAPI(
    title="Task Manager API",
    # Keep the documented validation response in sync with our error handler.
    responses={422: {"model": ErrorResponse}},
)


# This data lasts only as long as this process does. Restarting clears it.
_tasks: dict[UUID, Task] = {}


async def get_task_store() -> dict[UUID, Task]:
    """Bonus A: give routes their storage through a replaceable dependency."""
    return _tasks


TaskStore = Annotated[dict[UUID, Task], Depends(get_task_store)]


def find_task(task_id: UUID, store: dict[UUID, Task]) -> Task:
    # Share the lookup so GET, PATCH, and DELETE agree on missing tasks.
    task = store.get(task_id)
    if task is None:
        raise HTTPException(status_code=404, detail="Task not found.")
    return task


def log_task_event(action: str, task_id: UUID) -> None:
    """Bonus C: append a small event record after the response is sent."""
    timestamp = datetime.now(timezone.utc).isoformat()
    try:
        # Background jobs can run together. Keep each complete line together.
        with _log_lock, LOG_FILE.open("a", encoding="utf-8") as log_file:
            log_file.write(f"{timestamp} {action} {task_id}\n")
    except OSError:
        # The response has already been sent. Report a file error on the server;
        # the task was still created or deleted successfully.
        logger.exception("Could not write task event for %s", task_id)


@app.exception_handler(RequestValidationError)
async def handle_validation_error(
    request: Request, exc: RequestValidationError
) -> JSONResponse:
    # FastAPI normally returns a list of validation errors. The assessment asks
    # for a string under "detail", so include the field name in each message.
    messages = []
    for error in exc.errors():
        field = ".".join(str(part) for part in error["loc"])
        messages.append(f"{field}: {error['msg']}")
    return JSONResponse(status_code=422, content={"detail": "; ".join(messages)})


@app.exception_handler(StarletteHTTPException)
async def handle_http_error(
    request: Request, exc: StarletteHTTPException
) -> JSONResponse:
    # Starlette also raises errors for unknown URLs and unsupported methods.
    detail = exc.detail
    if exc.status_code == 404 and "route" not in request.scope:
        detail = "Route not found. See /docs for available endpoints."
    return JSONResponse(
        status_code=exc.status_code,
        content={"detail": str(detail)},
        headers=exc.headers,  # Preserve useful headers such as Allow on a 405.
    )


@app.exception_handler(Exception)
async def handle_unexpected_error(request: Request, exc: Exception) -> JSONResponse:
    # Keep debugging details in the server log, rather than exposing them to clients.
    logger.exception("Unexpected error during %s %s", request.method, request.url.path)
    return JSONResponse(status_code=500, content={"detail": "Internal server error."})


# These handlers do small, in-memory operations; file writes run in the background.
@app.post("/tasks", response_model=Task, status_code=status.HTTP_201_CREATED)
async def create_task(
    payload: TaskCreate,
    response: Response,
    store: TaskStore,
    background_tasks: BackgroundTasks,
) -> Task:
    task = Task(**payload.model_dump())
    store[task.id] = task
    response.headers["Location"] = f"/tasks/{task.id}"
    background_tasks.add_task(log_task_event, "created", task.id)
    return task


@app.get("/tasks", response_model=TaskPage)
async def list_tasks(
    store: TaskStore,
    completed: bool | None = None,
    limit: Annotated[int, Query(ge=1, le=100)] = 10,
    offset: Annotated[int, Query(ge=0)] = 0,
) -> TaskPage:
    tasks = list(store.values())
    # Check for None: completed=False is a real filter and must not be skipped.
    if completed is not None:
        tasks = [task for task in tasks if task.completed == completed]

    # Bonus B: count after filtering, then take a normal Python list slice.
    total = len(tasks)
    return TaskPage(
        total=total,
        items=tasks[offset : offset + limit],
        limit=limit,
        offset=offset,
        next_offset=offset + limit if offset + limit < total else None,
        previous_offset=max(0, offset - limit) if offset > 0 else None,
    )


@app.get("/tasks/{task_id}", response_model=Task)
async def get_task(task_id: UUID, store: TaskStore) -> Task:
    return find_task(task_id, store)


@app.patch("/tasks/{task_id}", response_model=Task)
async def update_task(task_id: UUID, payload: TaskUpdate, store: TaskStore) -> Task:
    task = find_task(task_id, store)

    # Only replace fields the caller actually sent. Otherwise a request to change
    # the title could accidentally reset completed or erase the description.
    changes = payload.model_dump(exclude_unset=True)
    # TaskUpdate has already validated these values before the handler runs.
    updated_task = task.model_copy(update=changes)
    store[task_id] = updated_task
    return updated_task


@app.delete("/tasks/{task_id}", status_code=status.HTTP_204_NO_CONTENT)
async def delete_task(
    task_id: UUID, store: TaskStore, background_tasks: BackgroundTasks
) -> Response:
    find_task(task_id, store)
    del store[task_id]
    background_tasks.add_task(log_task_event, "deleted", task_id)
    # A 204 response has no body, including no JSON null.
    return Response(status_code=status.HTTP_204_NO_CONTENT)
